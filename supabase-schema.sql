create table if not exists public.agent_config (
  key text primary key,
  value text not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.training_material (
  id integer primary key default 1 check (id = 1),
  title text not null default 'Base principal do agente',
  content text not null default '',
  source text,
  active boolean not null default true,
  updated_at timestamptz not null default now()
);

create table if not exists public.conversations (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now()
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  conversation_id uuid not null references public.conversations(id) on delete cascade,
  role text not null check (role in ('system', 'user', 'assistant')),
  content text not null,
  created_at timestamptz not null default now()
);

create index if not exists idx_messages_conversation on public.messages(conversation_id, id);

alter table public.agent_config enable row level security;
alter table public.training_material enable row level security;
alter table public.conversations enable row level security;
alter table public.messages enable row level security;
