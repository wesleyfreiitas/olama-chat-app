create table if not exists public.agent_config (
  key text primary key,
  value text not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.training_material (
  id integer primary key default 1 check (id = 1),
  title text not null default 'Base principal do agente',
  content text not null default '',
  source text,
  active boolean not null default true,
  updated_at timestamptz not null default now()
);

create extension if not exists vector with schema extensions;

create table if not exists public.training_chunks (
  id bigint generated by default as identity primary key,
  material_id integer not null references public.training_material(id) on delete cascade,
  chunk_index integer not null,
  content text not null,
  embedding extensions.vector(768) not null,
  created_at timestamptz not null default now(),
  unique (material_id, chunk_index)
);

create index if not exists idx_training_chunks_embedding
  on public.training_chunks using hnsw (embedding vector_cosine_ops);

create or replace function public.match_training_chunks(
  query_embedding extensions.vector(768),
  match_threshold float default 0.25,
  match_count int default 6
)
returns table (id bigint, content text, similarity float)
language sql stable
as $$
  select c.id, c.content, 1 - (c.embedding <=> query_embedding) as similarity
  from public.training_chunks c
  where 1 - (c.embedding <=> query_embedding) >= match_threshold
  order by c.embedding <=> query_embedding
  limit match_count;
$$;

create table if not exists public.conversations (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now()
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  conversation_id uuid not null references public.conversations(id) on delete cascade,
  role text not null check (role in ('system', 'user', 'assistant')),
  content text not null,
  created_at timestamptz not null default now()
);

create index if not exists idx_messages_conversation on public.messages(conversation_id, id);

alter table public.agent_config enable row level security;
